// Offline render contract for the generated root site (session arena-79cc0bd5).
//
// The site is pre-rendered by site_build, so it must be correct before any
// JavaScript runs — and still correct after it does. jsdom boots every generated
// page with a deliberately failing fetch (no network in CI) and checks:
//
//   1. no script error escapes, and no placeholder text reaches the DOM
//      ("undefined", "NaN", "[object Object]", raw "None");
//   2. the topbar contract holds: #livePill (which assets/desk.js rewrites when a
//      stream or poll lands) and #snapshotAge (which extras.age_label renders so a
//      stale snapshot is never mistaken for a live one) both exist;
//   3. every internal link on the page resolves to a file in the repo, and every
//      link this project chose is https;
//   4. the live desk keeps the two scrolling chats and the three time-window tabs.
//
// It is a *contract* test, not a duplicate of the unit suites: if a generator
// change renames an id or drops a nav entry, this fails on the PR that did it,
// before the scheduled collector publishes the broken page to GitHub Pages.
//
// Run: node tools/root_pages_render.mjs   (needs jsdom, declared in package.json)
import { JSDOM, VirtualConsole } from "jsdom";
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PAGES = ["index.html", "live.html", "trades.html", "resolutions.html",
  "suggestions.html", "methodology.html", "review.html", "summary.html",
  "categories/gas-prices.html", "categories/elections.html", "categories/culture.html",
  "categories/crypto.html", "categories/golf.html"];
const NAV_TARGETS = ["trades.html", "resolutions.html", "suggestions.html",
  "review.html", "methodology.html"];

const PLACEHOLDERS = ["undefined", "NaN", "[object Object]", "None<", "null<"];
let failures = 0;
const ok = (cond, msg) => { if (!cond) { failures++; console.error("  FAIL " + msg); } };

function collect(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === ".git" || name === "node_modules" || name === "_site") continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) collect(p, acc); else acc.push(p);
  }
  return acc;
}
const FILES = new Set(collect(ROOT));

for (const page of PAGES) {
  const selfName = page.split("/").pop();
  const path = join(ROOT, page);
  if (!existsSync(path)) { failures++; console.error(`  FAIL missing page ${page}`); continue; }
  const html = readFileSync(path, "utf8");
  const errors = [];
  const vc = new VirtualConsole();
  vc.on("jsdomError", (e) => errors.push(e.message || String(e)));
  vc.on("error", (m) => errors.push(String(m)));

  const dom = new JSDOM(html, {
    runScripts: "dangerously",
    pretendToBeVisual: true,
    virtualConsole: vc,
    url: "https://wingbangboozle1-lang.github.io/Trade2/" + page,
    beforeParse(win) {
      // Offline on purpose. The snapshot is inline or pre-rendered, so a failing
      // fetch must degrade the page, never break it.
      win.fetch = () => Promise.reject(new Error("offline by design"));
      win.EventSource = undefined;
    },
  });
  await new Promise((r) => setTimeout(r, 60));

  const doc = dom.window.document;
  // Read visible text only: a script body legitimately contains isNaN(), which
  // is not a placeholder leak.
  for (const el of doc.querySelectorAll("script, style")) el.remove();
  const text = doc.body.textContent.replace(/\s+/g, " ");
  const label = `${page}:`;

  ok(errors.length === 0, `${label} script errors: ${errors.slice(0, 2).join(" | ")}`);
  for (const bad of PLACEHOLDERS) ok(!text.includes(bad), `${label} placeholder "${bad}" rendered`);

  // summary.html is the one hand-authored page in the set: it carries a static
  // "SOURCE REVIEW" badge instead of a live topbar, on purpose, because it is a
  // document rather than a market view. Every other page is generated by
  // site_build and must expose both hooks.
  const generated = selfName !== "summary.html";
  if (generated) {
    ok(!!doc.getElementById("livePill"), `${label} no #livePill for desk.js to update`);
  }
  if (doc.querySelector(".topbar")) {
    const age = doc.getElementById("snapshotAge");
    ok(!!age, `${label} topbar has no #snapshotAge freshness marker`);
    if (age) ok(age.textContent.trim().length > 0, `${label} #snapshotAge is empty`);
  }

  for (const target of NAV_TARGETS) {
    if (target === selfName) continue;
    ok(!!doc.querySelector(`a[href$="${target}"]`), `${label} nav is missing ${target}`);
  }

  for (const a of doc.querySelectorAll("a[href]")) {
    const href = a.getAttribute("href");
    if (!href || href.startsWith("#") || href.startsWith("mailto:")) continue;
    if (/^https?:/.test(href)) {
      // Links copied verbatim out of Kalshi's own records stay exactly as the API
      // returned them (some settlement sources are http://); only links this
      // project chose are held to https.
      if (href.startsWith("http://")) {
        ok(/nbcsports|espn|pgatour|aaa|cfbenchmarks|ap\.org|reuters/i.test(href),
          `${label} we chose an insecure link: ${href}`);
      }
      continue;
    }
    ok(FILES.has(resolve(dirname(path), href.split("#")[0])), `${label} broken internal link ${href}`);
  }
  dom.window.close();
}

const desk = readFileSync(join(ROOT, "live.html"), "utf8");
ok(/id="feedAll"/.test(desk) && /id="feedModel"/.test(desk),
  "live.html lost one of the two scrolling chats (feedAll / feedModel)");
for (const w of ["seconds", "minutes", "hours"]) {
  ok(desk.includes(`data-window="${w}"`), `live.html lost the ${w} window tab`);
}

console.log(failures === 0
  ? `ALL PASS — ${PAGES.length} root pages rendered offline, ${FILES.size} files linked against`
  : `${failures} FAILURE(S)`);
process.exit(failures === 0 ? 0 : 1);
